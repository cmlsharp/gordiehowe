// GordieHowe compile cache:
// a compiled system's realized program (realized_program.h) on disk, so
// that compiling the same relation under the same profile again builds its
// domains from it in place of planning, emitting and scheduling.
//
// What is cached: the realized program, the compiler's last stage, which
// the domains are built from on a miss as on a hit (system.h's compile):
// its elements (every predicate with its target, the batches with their
// parts, the Boolean checks, the circuits' emission orders) and, per
// domain, its realization (ir::DomainRealization: the decisions' reasons
// and costs, the packing chains, the Ligero choice, and with a GKR circuit
// the circuit as Longfellow's scheduler returns it: header, id, the packed
// bits it chose, each layer's quad in its compressed form). No certificate
// of the Lean export is cached; the export computes them from the program.
// A hit runs the relation code and the lowerings, whose closures cannot be
// stored, and binds each element to its declaration: the affine and
// batched forms of the placed predicates, the batch kernels and the affine
// rows are built from the declarations the elements name. It counts the
// circuit inputs without building a circuit, and runs no provisional pass,
// placement rule, chain choice, tableau search, emission, scheduling or
// circuit id. Cheap derived state (cells, the packing tree from the stored
// chains, the tree plan, the prefix subfield test, routing) is computed as
// on a miss.
//
// The key covers every input of the domains' compilation: the graph after
// pad allocation (each node's kind, field, type, phase, pad, dependencies
// and description bytes, which hold the expressions), each domain's
// declarations (predicates and their expressions, placement pins, circuit
// constraints, affine rows, triples, batched relations, views, bindings,
// range requests), each domain's profile (field, Ligero parameters and
// target, placement and stage rates, packing tree degree), the compile
// profile, the lowerings' summaries and scopes, the compile options that
// force its decisions (compile_options.h), the field set, and the compiler
// digest: a digest of the compiler's, the library functions' and the
// examples' sources (kCompilerDigest, generated by CMake).
// A circuit constraint written as a closure is keyed by a description its
// lowering supplies (assert_in's and the range lowering's lookups, the
// MAC's H side); a closure without one makes the system uncacheable.
//
// A hit is checked: the file's own hash, the key in its header, each
// domain against the program (every declaration of the domain is an
// element of the program and every element on the domain one of its
// declarations, the circuit's input counts against the counted inputs),
// and the system digest, recomputed from the built system, against the
// digest stored with the entry. A failed check compiles afresh and
// replaces the entry.
//
// Where: CompileCache::dir, which compile() takes in its options
// (CompileOptions::cache; empty: off). Writes go to a temporary file renamed
// into place. Entries are never evicted; delete the directory to clear it.

