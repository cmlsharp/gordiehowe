"""Write the paper's Lean names from the paper manifest, GordieHowe/PaperManifest.lean.

The manifest pairs each machine-checked paper result with its Lean declaration, written as a name
literal that fails to elaborate when the declaration does not exist, so a renamed declaration
breaks the Lean build. This script writes the names into the paper's LaTeX source, the directory
given by --paper-dir:

* generated/lean-names.tex: for every entry `key`, the targets of `\\leanref[style]{key}`
  (macros.tex), with the styles `rel` (the default: the name without its leading `GordieHowe.`), `full`
  and `n` (the last `n` components);
* the rows of the formalization table, between the GENERATED markers in
  sections/formal-appendix.tex (the appendix `app:formal`), from `appendixTable`: a row with a
  `heading` opens a group of the table, and the other rows pair a statement with its Lean
  declarations.

It also checks the paper against the manifest: every `\\leanref` key and every table key is an
entry, every entry's label is a label of the paper, and no compiled .tex file prints a Lean name
through `\\leanname` or `\\nolinkurl` outside the generated table.

Usage: scripts/paper_manifest.py [--check] [--paper-dir DIR]
  --paper-dir DIR  the paper's LaTeX source (the directory of main.tex); the script writes
                   DIR/generated/lean-names.tex and the table of DIR/sections/formal-appendix.tex.
                   Without it, the script only reads the manifest and reports its counts.
  --check          write nothing; exit 1 if a generated file under DIR is out of date or a check
                   fails.

The comment lines that open the generated table and lean-names.tex name the script that wrote
them; an existing comment line of that form is kept, whatever path it names.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MANIFEST = os.path.join(HERE, '..', 'GordieHowe', 'PaperManifest.lean')
NAMES = os.path.join('generated', 'lean-names.tex')
TABLE_FILE = os.path.join('sections', 'formal-appendix.tex')
BEGIN = '% BEGIN GENERATED by formal/scripts/paper_manifest.py from GordieHowe/PaperManifest.lean'
BEGIN_LINE = re.compile(r'^% BEGIN GENERATED by \S*paper_manifest\.py from GordieHowe/PaperManifest\.lean$', re.M)
END = '% END GENERATED'
NAMES_HEADER = '% Generated by formal/scripts/paper_manifest.py from formal/GordieHowe/PaperManifest.lean.'
NAMES_HEADER_LINE = re.compile(r'% Generated by \S*paper_manifest\.py from \S*PaperManifest\.lean\.')


class ManifestError(Exception):
    pass


# --- Reading the manifest -------------------------------------------------------------------

TOKEN = re.compile(r'''
    (?P<ws>\s+)
  | (?P<comment>--[^\n]*)
  | (?P<string>"(?:[^"\\]|\\.)*")
  | (?P<name>``[A-Za-z_][A-Za-z0-9_'.]*)
  | (?P<punct>:=|\+\+|[{}\[\],])
  | (?P<ident>[A-Za-z_][A-Za-z0-9_']*)
''', re.VERBOSE)

ESCAPES = {'\\': '\\', '"': '"', "'": "'", 'n': '\n', 't': '\t'}


def unescape(lit):
    body, out, i = lit[1:-1], [], 0
    while i < len(body):
        c = body[i]
        if c == '\\':
            e = body[i + 1]
            if e not in ESCAPES:
                raise ManifestError(f'unsupported escape \\{e} in {lit[:40]}')
            out.append(ESCAPES[e])
            i += 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def tokens(text):
    pos, out = 0, []
    while pos < len(text):
        m = TOKEN.match(text, pos)
        if not m:
            raise ManifestError(f'cannot read the manifest at {text[pos:pos + 40]!r}')
        kind = m.lastgroup
        if kind not in ('ws', 'comment'):
            out.append((kind, m.group()))
        pos = m.end()
    return out


def list_body(text, decl):
    """The text of the list literal of `def <decl> : ... := [ ... ]`, closed by a line `]`."""
    m = re.search(r'^def ' + decl + r' : [^\n]*:= \[\n(.*?)^\]$', text, re.M | re.S)
    if not m:
        raise ManifestError(f'no list literal for def {decl}')
    return m.group(1)


def parse_value(toks, i):
    kind, val = toks[i]
    if kind == 'string':
        parts = [unescape(val)]
        i += 1
        while i < len(toks) and toks[i] == ('punct', '++'):
            if toks[i + 1][0] != 'string':
                raise ManifestError('++ must join string literals')
            parts.append(unescape(toks[i + 1][1]))
            i += 2
        return ''.join(parts), i
    if kind == 'name':
        return val[2:], i + 1
    if val == '[':
        names, i = [], i + 1
        while toks[i] != ('punct', ']'):
            if toks[i][0] != 'name':
                raise ManifestError(f'expected a name literal, got {toks[i][1]}')
            names.append(toks[i][1][2:])
            i += 1
            if toks[i] == ('punct', ','):
                i += 1
        return names, i + 1
    raise ManifestError(f'unexpected value {val}')


def parse_records(body):
    toks, i, recs = tokens(body), 0, []
    while i < len(toks):
        if toks[i] != ('punct', '{'):
            raise ManifestError(f'expected {{, got {toks[i][1]}')
        i, rec = i + 1, {}
        while toks[i] != ('punct', '}'):
            field = toks[i][1]
            if toks[i][0] != 'ident' or toks[i + 1] != ('punct', ':='):
                raise ManifestError(f'expected a field, got {field}')
            rec[field], i = parse_value(toks, i + 2)
            if toks[i] == ('punct', ','):
                i += 1
        recs.append(rec)
        i += 1
        if i < len(toks) and toks[i] == ('punct', ','):
            i += 1
    return recs


def read_manifest(path):
    text = open(path, encoding='utf-8').read()
    entries = parse_records(list_body(text, 'entries'))
    rows = parse_records(list_body(text, 'appendixTable'))
    for e in entries:
        if set(e) - {'key', 'label', 'decl', 'instances'} or not {'key', 'label', 'decl'} <= set(e):
            raise ManifestError(f'malformed entry {e}')
    for r in rows:
        if set(r) != {'statement', 'lean'} and set(r) != {'heading'}:
            raise ManifestError(f'malformed table row {r}')
    return entries, rows


# --- Printing names -------------------------------------------------------------------------

def shown(decl, style):
    parts = decl.split('.')
    if style == 'rel':
        return '.'.join(parts[1:]) if parts[0] == 'GordieHowe' and len(parts) > 1 else decl
    if style == 'full':
        return decl
    n = int(style)
    if not 1 <= n <= len(parts):
        raise ManifestError(f'style {style} out of range for {decl}')
    return '.'.join(parts[-n:])


def styles(decl):
    return ['rel', 'full'] + [str(n) for n in range(1, decl.count('.') + 2)]


PLACEHOLDER = re.compile(r'\{([a-z0-9-]+)(?::(full|[0-9]+))?\}')


def fill(template, by_key, used):
    def sub(m):
        key, style = m.group(1), m.group(2) or 'rel'
        if key not in by_key:
            raise ManifestError(f'table row names unknown entry {key}')
        used.add(key)
        return '\\leanname{' + shown(by_key[key]['decl'], style) + '}'
    return PLACEHOLDER.sub(sub, template)


def names_file(entries, header=NAMES_HEADER):
    lines = [header,
             '% Do not edit: change the manifest and rerun the script.']
    for e in entries:
        for s in styles(e['decl']):
            lines.append('\\expandafter\\def\\csname leanref:%s:%s\\endcsname{\\leanname{%s}}'
                         % (e['key'], s, shown(e['decl'], s)))
    return '\n'.join(lines) + '\n'


def table_block(rows, by_key, used, begin=BEGIN):
    out = [begin]
    for i, r in enumerate(rows):
        if 'heading' in r:
            if i > 0:
                out.append('\\midrule')
            out.append('\\multicolumn{2}{@{}>{\\raggedright\\arraybackslash}p{0.96\\textwidth}@{}}{\\textit{' + r['heading'] + '}} \\\\*')
            continue
        out.append(fill(r['statement'], by_key, used) + ' & ' + fill(r['lean'], by_key, used) + ' \\\\')
    out.append(END)
    return '\n'.join(out)


# --- Checking the paper ---------------------------------------------------------------------

def compiled_files(paper):
    """The .tex files main.tex inputs, recursively, skipping commented-out inputs."""
    seen, todo = [], ['main.tex']
    while todo:
        f = todo.pop(0)
        if f in seen or not os.path.exists(os.path.join(paper, f)):
            continue
        seen.append(f)
        for line in open(os.path.join(paper, f), encoding='utf-8'):
            code = re.split(r'(?<!\\)%', line, maxsplit=1)[0]
            for m in re.finditer(r'\\input\{([^}]*)\}', code):
                name = m.group(1)
                todo.append(name if name.endswith('.tex') else name + '.tex')
    return seen


def strip_comments(text):
    return '\n'.join(re.split(r'(?<!\\)%', l, maxsplit=1)[0] for l in text.split('\n'))


def check_paper(paper, entries, by_key, used):
    problems = []
    files = compiled_files(paper)
    labels = set()
    for f in files:
        labels |= set(re.findall(r'\\label\{([^}]*)\}', open(os.path.join(paper, f), encoding='utf-8').read()))
    for e in entries:
        if e['label'] not in labels:
            problems.append(f"entry {e['key']}: no \\label{{{e['label']}}} in the compiled paper")
    for f in files:
        if f == NAMES:
            continue
        text = open(os.path.join(paper, f), encoding='utf-8').read()
        m = BEGIN_LINE.search(text) if f == TABLE_FILE else None
        if m and END in text:
            a, b = m.start(), text.index(END)
            text = text[:a] + text[b:]
        code = strip_comments(text)
        for m in re.finditer(r'\\leanref(?:\[(full|rel|[0-9]+)\])?\{([^}]*)\}', code):
            style, key = m.group(1) or 'rel', m.group(2)
            if key not in by_key:
                problems.append(f'{f}: \\leanref{{{key}}} names no manifest entry')
            elif style not in styles(by_key[key]['decl']):
                problems.append(f'{f}: \\leanref[{style}]{{{key}}}: style out of range')
            else:
                used.add(key)
        if f == 'macros.tex':
            continue
        for m in re.finditer(r'\\(leanname|nolinkurl)\{([^}]*)\}', code):
            arg = m.group(2)
            if '/' not in arg and arg != '#1':
                problems.append(f'{f}: Lean name {arg} printed outside the manifest; use \\leanref')
    return problems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--paper-dir', metavar='DIR', default=None)
    args = ap.parse_args()
    try:
        entries, rows = read_manifest(MANIFEST)
        by_key = {}
        for e in entries:
            if e['key'] in by_key:
                raise ManifestError(f"duplicate key {e['key']}")
            by_key[e['key']] = e
        used = set()
        if args.paper_dir is None:
            table_block(rows, by_key, used)
            print(f"{len(entries)} entries, {sum('heading' not in r for r in rows)} table rows; "
                  'no --paper-dir, so no paper was written or checked')
            return 0
        paper = os.path.normpath(args.paper_dir)
        table_path = os.path.join(paper, TABLE_FILE)
        names_path = os.path.join(paper, NAMES)
        text = open(table_path, encoding='utf-8').read()
        begins = BEGIN_LINE.findall(text)
        if len(begins) != 1 or text.count(END) != 1:
            raise ManifestError(f'{TABLE_FILE} needs one pair of GENERATED markers')
        old_names = open(names_path, encoding='utf-8').read() if os.path.exists(names_path) else None
        first = old_names.split('\n', 1)[0] if old_names else ''
        names = names_file(entries, first if NAMES_HEADER_LINE.fullmatch(first) else NAMES_HEADER)
        block = table_block(rows, by_key, used, begins[0])
    except (ManifestError, OSError) as err:
        print(f'paper_manifest.py: {err}', file=sys.stderr)
        return 1

    a, b = BEGIN_LINE.search(text).start(), text.index(END) + len(END)
    new_text = text[:a] + block + text[b:]

    stale = [p for p, old, new in ((names_path, old_names, names), (table_path, text, new_text))
             if old != new]

    problems = check_paper(paper, entries, by_key, used)
    if args.check:
        for p in stale:
            problems.append(f'{os.path.relpath(p, paper)} is out of date; run scripts/paper_manifest.py --paper-dir {paper}')
    else:
        for p, content in ((names_path, names), (table_path, new_text)):
            if p in stale:
                os.makedirs(os.path.dirname(p), exist_ok=True)
                with open(p + '.tmp', 'w', encoding='utf-8') as fh:
                    fh.write(content)
                os.replace(p + '.tmp', p)
                print(f'wrote {os.path.relpath(p, paper)}')
    unprinted = [e['key'] for e in entries if e['key'] not in used]
    print(f"{len(entries)} entries, {sum('heading' not in r for r in rows)} table rows; "
          f'{len(entries) - len(unprinted)} printed, {len(unprinted)} checked only '
          f'({", ".join(unprinted)})')
    for p in problems:
        print(f'paper_manifest.py: {p}', file=sys.stderr)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
