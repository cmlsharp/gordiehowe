"""Deterministic RSA-2048 PKCS#1 v1.5 (SHA-256) test vectors for
rsa_pkcs1.h, printed as the C++ header rsa_vectors.h.

  python3 -I rsa_vectors.py > rsa_vectors.h

The primes are the first primes (Miller-Rabin, the first 40 prime bases)
above 1024-bit starting points expanded by SHA-256 from fixed labels,
their top two bits set, so N has exactly 2048 bits. A second
modulus from two other primes serves the wrong-key test. Message i of n
bytes is byte j = (31 j + 7 + i) mod 256; signatures are given for
messages of 13, 64, 1000 and 2048 bytes. Each signature is EM^d mod N
with EM = 0x00 01 FF..FF 00 || DigestInfo(SHA-256) || SHA-256(m)
(RFC 8017, section 9.2), and is checked against s^65537 mod N.
"""
import hashlib

SMALL = [p for p in range(2, 200) if all(p % q for q in range(2, p))][:40]


def is_prime(n):
    if n < 2:
        return False
    for p in SMALL:
        if n % p == 0:
            return n == p
    d, r = n - 1, 0
    while d % 2 == 0:
        d //= 2
        r += 1
    for a in SMALL:
        x = pow(a, d, n)
        if x in (1, n - 1):
            continue
        for _ in range(r - 1):
            x = x * x % n
            if x == n - 1:
                break
        else:
            return False
    return True


def next_prime(n):
    n |= 1
    while not is_prime(n):
        n += 2
    return n


E = 65537
DIGEST_INFO = bytes.fromhex("3031300d060960864801650304020105000420")


def start(label):
    b = b"".join(hashlib.sha256(b"%s/%d" % (label, i)).digest()
                 for i in range(4))
    return int.from_bytes(b, "big") | (3 << 1022)


def key(label_p, label_q):
    p = next_prime(start(label_p))
    q = next_prime(start(label_q))
    n = p * q
    assert n.bit_length() == 2048
    lam = (p - 1) * (q - 1)
    d = pow(E, -1, lam)
    return n, d


def message(n, i=0):
    return bytes((31 * j + 7 + i) % 256 for j in range(n))


def em(msg):
    t = DIGEST_INFO + hashlib.sha256(msg).digest()
    ps = b"\xff" * (256 - 3 - len(t))
    return int.from_bytes(b"\x00\x01" + ps + b"\x00" + t, "big")


def carr(name, b):
    rows = []
    for k in range(0, len(b), 16):
        rows.append("    " + ", ".join("0x%02x" % x for x in b[k:k + 16]) + ",")
    return ("inline constexpr uint8_t %s[%d] = {\n" % (name, len(b)) +
            "\n".join(rows) + "\n};\n")


def main():
    n, d = key(b"gordiehowe-rsa-p", b"gordiehowe-rsa-q")
    n2, _ = key(b"gordiehowe-rsa-p2", b"gordiehowe-rsa-q2")
    out = []
    out.append("// Generated by rsa_vectors.py (python3 -I rsa_vectors.py > "
               "rsa_vectors.h);\n// do not edit.\n")
    out.append("#ifndef PRIVACY_PROOFS_ZK_LIB_GORDIEHOWE_EXAMPLES_RSA_VECTORS_H_\n"
               "#define PRIVACY_PROOFS_ZK_LIB_GORDIEHOWE_EXAMPLES_RSA_VECTORS_H_\n\n"
               "#include <cstdint>\n\n"
               "namespace proofs::gordiehowe::examples::rsa::vectors {\n\n")
    out.append("// The modulus N, big-endian.\n")
    out.append(carr("kN", n.to_bytes(256, "big")))
    out.append("// Another 2048-bit modulus (the wrong-key test), big-endian.\n")
    out.append(carr("kN2", n2.to_bytes(256, "big")))
    for ln in (13, 64, 1000, 2048):
        m = message(ln)
        s = pow(em(m), d, n)
        assert pow(s, E, n) == em(m)
        out.append("// The signature of message(%d), big-endian; its EM.\n" % ln)
        out.append(carr("kSig%d" % ln, s.to_bytes(256, "big")))
        out.append(carr("kEm%d" % ln, em(m).to_bytes(256, "big")))
    out.append("\n}  // namespace proofs::gordiehowe::examples::rsa::vectors\n\n"
               "#endif  // PRIVACY_PROOFS_ZK_LIB_GORDIEHOWE_EXAMPLES_RSA_VECTORS_H_\n")
    print("".join(out), end="")


if __name__ == "__main__":
    main()
