"""Carry audit records across a declaration renaming (the namespace and naming pass).

Inputs: `audit/renames.tsv` (`<old>\t<new>`), `audit/statement_closure.txt` as regenerated by
`scripts/StatementClosure.lean` after the renaming (third column the fingerprint, optional fourth
column the fingerprint with every renamed constant replaced by its old name), and
`audit/audited.txt`.

For every ledger entry, the declaration is looked up under its new name. If the closure's
rename-normalized fingerprint equals the recorded fingerprint, the statement is the audited one up
to the renaming: the entry moves to the new name, keeps its commit and audit reference, gains
`; renamed <tag>` in the reference column and records the new fingerprint. Otherwise the entry is
left for re-audit (renamed, with its old fingerprint, so `check.sh` reports it as changed).

Usage: scripts/carry_audits.py <tag> [--write]
"""
import sys

tag = sys.argv[1] if len(sys.argv) > 1 else 'S3'
write = '--write' in sys.argv

renames = {}
for line in open('audit/renames.tsv'):
    if line.startswith('#') or not line.strip():
        continue
    o, n = line.rstrip('\n').split('\t')
    renames[o] = n

raw, norm = {}, {}
for line in open('audit/statement_closure.txt'):
    if line.startswith('#'):
        continue
    p = line.rstrip('\n').split('\t')
    if len(p) >= 3:
        raw[p[1]] = p[2]
        norm[p[1]] = p[3] if len(p) > 3 else p[2]

header, entries = [], []
for line in open('audit/audited.txt'):
    if line.startswith('#') or not line.strip():
        header.append(line.rstrip('\n'))
        continue
    p = line.rstrip('\n').split('\t')
    while len(p) < 4:
        p.append('')
    entries.append(p)

carried = renamed_only = reaudit = untouched = gone = 0
reaudits = []
out = []
for name, commit, ref, fp in entries:
    new = renames.get(name, name)
    if new not in raw:
        gone += 1
        out.append([new, commit, ref, fp])
        continue
    if fp and fp == raw[new] and new == name:
        untouched += 1
        out.append([name, commit, ref, fp])
        continue
    if fp and norm[new] == fp:
        if new != name:
            carried += 1
        else:
            renamed_only += 1
        out.append([new, commit, f'{ref}; renamed {tag}', raw[new]])
    else:
        reaudit += 1
        reaudits.append(f'{name} -> {new}' if new != name else name)
        out.append([new, commit, ref, fp])

print(f'ledger entries: {len(entries)}; carried across a rename: {carried}; '
      f'fingerprint refreshed (mentions a renamed constant): {renamed_only}; unchanged: {untouched}; '
      f're-audit: {reaudit}; not in the closure: {gone}')
for r in reaudits[:60]:
    print('  re-audit:', r)
if write:
    seen = set()
    with open('audit/audited.txt.tmp', 'w') as f:
        for h in header:
            f.write(h + '\n')
        for e in sorted(out, key=lambda e: e[0]):
            if e[0] in seen:
                continue
            seen.add(e[0])
            f.write('\t'.join(e) + '\n')
    import os
    os.replace('audit/audited.txt.tmp', 'audit/audited.txt')
