"""Write the stage-0 module of the kernel-mode certificate check.

`Check/Stage0/GordieHoweStage0.lean` (the library GordieHoweStage0, lakefile.toml) imports a fixed
set of kernel-mode check modules (`GordieHoweCheck.*` under `Check/Kernel/`). In kernel mode,
`scripts/check.sh --certs` builds it before the full build and stops when it fails. The kernel's
heartbeat limit is deterministic, so a leaf theorem that fails in the full build also fails here.

The set, in order, until the modules' costs reach the budget (`--budget-min` times `--jobs`
minutes of CPU time):
1. every module named with `--include`;
2. every module whose largest leaf theorem is predicted to cost at least `--risky-s` seconds;
3. the slowest modules.

A module that only composes (its command `compose_entry`, `compose_header` or `compose_circuit`)
is never selected: it checks nothing itself, and building it builds every module it imports (a
circuit's `Circuit` module imports all its entries). Its recorded timing is ignored too, which
also drops the timing of a module that checked leaves when it was recorded (the `Circuit` modules
before the header moved to `Header` modules).

The costs come from the timings of earlier builds (`--timings`: Lake's `Built <module> (<time>)`
lines, as `scripts/check.sh` saves them in `.lake/check/build_times.txt`), and otherwise from the
exporter's predictions (`--predicted`: the `GH_EMIT_PLAN_MODULES` lines a C++ export prints with
that variable set, `lib/gordiehowe/compiler/emit_export.h`: per module its predicted cost and
largest leaf in milliseconds). A recorded timing replaces the prediction. Modules that do not
exist under `Check/Kernel/` are skipped.
"""

import argparse
import os
from pathlib import Path
import re
import sys

OUT = Path("Check/Stage0/GordieHoweStage0.lean")
KERNEL = Path("Check/Kernel")
HEADER = """\
-- Copyright 2026 Chad Sharp and Paul Grubbs
-- SPDX-License-Identifier: Apache-2.0

-- Stage 0 of the kernel-mode certificate check (generated by scripts/stage0.py; do not edit):
-- the check modules most likely to fail or slowest, built first by scripts/check.sh.
module

"""


def parse_time(text):
    """Seconds of a Lake duration such as `12s`, `1.5s`, `340ms` or `2m 3s`."""
    total = 0.0
    for number, unit in re.findall(r"(\d+(?:\.\d+)?)\s*(ms|s|m|h)\b", text):
        total += float(number) * {"ms": 0.001, "s": 1, "m": 60, "h": 3600}[unit]
    return total


def read_timings(paths):
    """Module -> seconds, the largest recorded."""
    out = {}
    for path in paths:
        for line in Path(path).read_text(errors="replace").splitlines():
            m = re.search(r"Built (GordieHoweCheck\.\S+) \(([^)]*)\)", line)
            if m:
                out[m.group(1)] = max(out.get(m.group(1), 0.0), parse_time(m.group(2)))
    return out


def read_predicted(paths):
    """Module -> (seconds, largest leaf seconds)."""
    out = {}
    for path in paths:
        for line in Path(path).read_text(errors="replace").splitlines():
            m = re.search(r"GH_EMIT_PLAN_MODULES (\S+) (.*)$", line)
            if not m:
                continue
            for item in m.group(2).split():
                rel, cost, top = item.rsplit(":", 2)
                out[m.group(1) + "." + rel] = (int(cost) / 1000, int(top) / 1000)
    return out


def path(module):
    return KERNEL / (module.replace(".", "/") + ".lean")


def exists(module):
    return path(module).is_file()


COMPOSE = re.compile(r"^(compose_entry|compose_header|compose_circuit)\b", re.M)


def composes(module):
    """Whether the module only composes imported theorems (its command a `compose_*`)."""
    return exists(module) and COMPOSE.search(path(module).read_text(errors="replace")) is not None


def select(include, timings, predicted, risky_s, budget_s):
    """The modules in order and their costs (seconds)."""
    cost = {m: c for m, (c, _) in predicted.items()}
    cost.update(timings)
    cost = {m: c for m, c in cost.items() if not composes(m)}
    predicted = {m: x for m, x in predicted.items() if m in cost}
    chosen, total = [], 0.0

    def take(module):
        nonlocal total
        if module in chosen or not exists(module):
            return
        chosen.append(module)
        total += cost.get(module, 0.0)

    for module in include:
        take(module)
    for module, (_, top) in sorted(predicted.items(), key=lambda x: -x[1][1]):
        if top >= risky_s and total < budget_s:
            take(module)
    for module in sorted(cost, key=lambda m: -cost[m]):
        if total + cost[module] > budget_s:
            continue
        take(module)
    return chosen, total, cost


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--timings", action="append", default=[], help="Lake build log")
    parser.add_argument("--predicted", action="append", default=[], help="export log")
    parser.add_argument("--include", action="append", default=[], help="a module to include")
    parser.add_argument("--risky-s", type=float, default=100.0)
    parser.add_argument("--budget-min", type=float, default=30.0)
    parser.add_argument("--jobs", type=int, default=12)
    args = parser.parse_args(argv)
    os.chdir(Path(__file__).resolve().parent.parent)
    for module in args.include:
        if not exists(module):
            print(f"stage0.py: no module {module} under {KERNEL}", file=sys.stderr)
            return 2
        if composes(module):
            print(f"stage0.py: {module} only composes; include its part modules",
                  file=sys.stderr)
            return 2
    timings = read_timings(args.timings)
    predicted = read_predicted(args.predicted)
    chosen, total, cost = select(args.include, timings, predicted, args.risky_s,
                                 args.budget_min * 60 * args.jobs)
    text = HEADER + "".join(f"import {m}\n" for m in chosen)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"{OUT}: {len(chosen)} modules, {total / 3600:.2f} CPU-hours "
          f"({total / 60 / args.jobs:.1f} min at {args.jobs} jobs if they run in parallel)")
    for m in chosen:
        print(f"  {cost.get(m, 0.0):8.0f} s  {m}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
