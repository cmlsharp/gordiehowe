"""List the Longfellow files we changed, or print one file's diff against upstream.

With no options, writes docs/longfellow-changes.md from
third_party/longfellow/licensing.json:
per module, every modified or derived file with its upstream source and its
one-line summary. --check fails if the checked-in document is out of date.
--diff PATH prints PATH's unified diff against its upstream source at the
pinned commit, read from the upstream checkout (--upstream, default
comparisons/longfellow/upstream).
"""

import argparse
from collections import defaultdict
import difflib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs/longfellow-changes.md"
# Every file's licensing class, beside the vendored files' manifest.json.
LICENSING = "third_party/longfellow/licensing.json"


def load(root):
    return json.loads((root / LICENSING).read_text())


def pinned_commit(licensing):
    return licensing["upstream"].split()[-1]


def module(path):
    """A file's module: its directory, with the baselines grouped per baseline."""
    parts = Path(path).parts
    if parts[:3] == ("comparisons", "longfellow", "baselines"):
        return "/".join(parts[:4])
    return "/".join(parts[:-1])


def render(licensing):
    changed = [f for f in licensing["files"] if f["class"] in ("modified", "derived")]
    groups = defaultdict(list)
    for f in changed:
        groups[module(f["path"])].append(f)
    commit = pinned_commit(licensing)
    out = [
        "# Changes to Longfellow",
        "",
        "<!-- Generated by scripts/longfellow_changes.py from "
        "third_party/longfellow/licensing.json; "
        "do not edit. -->",
        "",
        f"Every file below is a Longfellow file we changed (modified, at its upstream path) "
        f"or a new file copying substantial Longfellow code (derived, with its upstream "
        f"source). Longfellow is google/longfellow-zk at `{commit[:8]}`. Files used "
        f"unchanged live under `third_party/longfellow/`, listed in its `manifest.json` "
        f"and checked by `scripts/check_vendor.py`.",
        "",
        "To print a file's full diff against the pinned upstream:",
        "",
        "```sh",
        "git submodule update --init comparisons/longfellow/upstream",
        "python3 scripts/longfellow_changes.py --diff lib/zk/zk_prover.h",
        "```",
        "",
        f"{sum(f['class'] == 'modified' for f in changed)} modified and "
        f"{sum(f['class'] == 'derived' for f in changed)} derived files.",
    ]
    # GordieHowe's stack (lib/) first, then the Longfellow baselines.
    for name in sorted(groups, key=lambda n: (n.startswith("comparisons/"), n)):
        out += ["", f"## `{name}`", "", "| File | Kind | Upstream source | Change |",
                "|---|---|---|---|"]
        for f in sorted(groups[name], key=lambda f: f["path"]):
            summary = (f["summary"] or "").replace("|", "\\|")
            out.append(f"| `{Path(f['path']).relative_to(name)}` | {f['class']} | "
                       f"`{f['upstream_source']}` | {summary} |")
    return "\n".join(out) + "\n"


def diff(licensing, path, upstream):
    rows = {f["path"]: f for f in licensing["files"]}
    row = rows.get(path)
    if row is None or row["class"] not in ("modified", "derived"):
        raise SystemExit(f"{path}: not a modified or derived Longfellow file")
    commit = pinned_commit(licensing)
    original = subprocess.run(
        ["git", "-C", str(upstream), "show", f"{commit}:{row['upstream_source']}"],
        check=True, capture_output=True, text=True).stdout
    ours = (ROOT / path).read_text()
    return "".join(difflib.unified_diff(
        original.splitlines(keepends=True), ours.splitlines(keepends=True),
        fromfile=f"upstream/{row['upstream_source']}", tofile=path))


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--diff", metavar="PATH", help="print PATH's diff against upstream")
    parser.add_argument("--upstream", type=Path, default=ROOT / "comparisons/longfellow/upstream",
                        help="the upstream Longfellow checkout")
    parser.add_argument("--check", action="store_true",
                        help="fail if docs/longfellow-changes.md is out of date")
    args = parser.parse_args()
    licensing = load(ROOT)
    if args.diff:
        sys.stdout.write(diff(licensing, args.diff, args.upstream))
        return 0
    text = render(licensing)
    if args.check:
        if DOC.read_text() != text:
            raise SystemExit("docs/longfellow-changes.md is out of date; "
                             "run scripts/longfellow_changes.py")
        return 0
    DOC.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
